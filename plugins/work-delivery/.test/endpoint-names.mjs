import assert from 'node:assert/strict'
import {
  APP_EXPOSE_ENDPOINT,
  APP_UNEXPOSE_ENDPOINT,
  SERVICE_ACTION_ENDPOINT,
  SERVICE_ADD_ENDPOINT,
  SERVICE_LOGS_ENDPOINT,
  SERVICE_REMOVE_ENDPOINT,
  STATE_ENDPOINT,
  TASK_APPROVE_ENDPOINT,
  TASK_CREATE_ENDPOINT,
  TASK_STATUS_ENDPOINT,
} from '../index.js'

const ENDPOINT_RE = /^\/api\/[a-z0-9-]+(?:\.[a-z0-9-]+)+$/

for (const ep of [
  STATE_ENDPOINT,
  TASK_CREATE_ENDPOINT,
  TASK_STATUS_ENDPOINT,
  TASK_APPROVE_ENDPOINT,
  APP_EXPOSE_ENDPOINT,
  APP_UNEXPOSE_ENDPOINT,
  SERVICE_ACTION_ENDPOINT,
  SERVICE_ADD_ENDPOINT,
  SERVICE_REMOVE_ENDPOINT,
  SERVICE_LOGS_ENDPOINT,
]) {
  assert.match(ep, ENDPOINT_RE, `Endpoint ${ep} must follow /api/<plugin>.<action> convention`)
}
console.log('endpoint-names ok')
