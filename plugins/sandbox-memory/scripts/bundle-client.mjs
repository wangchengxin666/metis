import { readFileSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const SRC_DIR = join(ROOT, 'src')
const TEMPLATE_PATH = join(ROOT, 'client.js.template')
const OUTPUT_PATH = join(ROOT, 'client.js')

const MODULE_FILES = [
  'shared/model.js',
  'client/locale.js',
  'client/styles.js',
  'client/icons.js',
  'client/tool-views.js',
  'client/memory-controller.js',
  'client/memory-page.js',
]

function stripModuleDirectives(source, filename) {
  const withoutImports = source.replace(/^import\s+[\s\S]*?\s+from\s+['"][^'"]+['"];?\s*\r?\n?/gm, '')
  const normalizedExports = withoutImports
    .replace(/^export\s+(const|let|var|function|async\s+function|class)\b/gm, '$1')
    .replace(/^export\s*\{[\s\S]*?\};?\s*\r?\n?/gm, '')
  return `// --- ${filename} ---\n${normalizedExports.trim()}\n`
}

export function renderClientBundle() {
  const template = readFileSync(TEMPLATE_PATH, 'utf8')
  const marker = '// __CLIENT_MODULES__'
  if (!template.includes(marker)) {
    throw new Error(`Missing ${marker} placeholder in ${TEMPLATE_PATH}`)
  }

  const combinedModules = MODULE_FILES
    .map((file) => stripModuleDirectives(readFileSync(join(SRC_DIR, file), 'utf8'), file))
    .join('\n')

  const indentedModules = combinedModules
    .split('\n')
    .map((line) => (line.length > 0 ? `    ${line}` : ''))
    .join('\n')

  return `// AUTO-GENERATED by scripts/bundle-client.mjs. Do not edit directly.\n${template.replace(marker, indentedModules.trimStart())}`
}

export function buildClientBundle() {
  const output = renderClientBundle()
  writeFileSync(OUTPUT_PATH, output, 'utf8')
  execFileSync(process.execPath, ['--check', OUTPUT_PATH], { stdio: 'pipe' })
  return OUTPUT_PATH
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = buildClientBundle()
  console.log(`Built ${out}`)
}
