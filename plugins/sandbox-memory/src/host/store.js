import { randomBytes } from 'node:crypto'
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'
import {
  buildSummary,
  computeTitleSimilarity,
  DEFAULT_SETTINGS,
  normalizeCategory,
  normalizeSettings,
  normalizeSource,
  normalizeTags,
  normalizeTitle,
  rankMemories,
  redactSecrets,
} from '../shared/model.js'

const MAX_MEMORIES = 500
const MAX_CONTENT_CHARS = 16000

export function resolveMemoryDir(config = {}, env = process.env) {
  if (typeof config.memoryDir === 'string' && config.memoryDir.trim()) {
    return config.memoryDir.trim()
  }
  const dshHome = String(config.dshHome || env.DSH_HOME || '').trim()
    || join(String(config.homeDir || env.HOME || '').trim() || homedir(), '.dsh')
  return join(dshHome, 'memory')
}

function generateMemoryId() {
  return `mem_${randomBytes(5).toString('hex')}`
}

function atomicWriteFile(filePath, content, mode = 0o600) {
  mkdirSync(dirname(filePath), { recursive: true })
  const tmpPath = `${filePath}.${process.pid}.${Date.now()}.tmp`
  writeFileSync(tmpPath, content, { encoding: 'utf8', mode })
  renameSync(tmpPath, filePath)
  try { chmodSync(filePath, mode) } catch {}
}

function sanitizeDedupeKey(raw) {
  return String(raw || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9\u4e00-\u9fff:_-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 96)
}

function renderEntryMarkdown(entry) {
  const tagsLine = entry.tags?.length ? entry.tags.join(', ') : ''
  const lines = [
    '---',
    `id: ${entry.id}`,
    `title: ${JSON.stringify(entry.title)}`,
    `category: ${entry.category}`,
    `source: ${entry.source}`,
    `enabled: ${entry.enabled !== false}`,
    `pinned: ${Boolean(entry.pinned)}`,
    ...(tagsLine ? [`tags: ${tagsLine}`] : []),
    ...(entry.dedupeKey ? [`dedupeKey: ${entry.dedupeKey}`] : []),
    `updatedAt: ${new Date(entry.updatedAt || Date.now()).toISOString()}`,
    '---',
    '',
    `# ${entry.title}`,
    '',
    entry.summary ? `> ${entry.summary}` : '',
    entry.summary ? '' : '',
    entry.content || entry.summary || '',
    '',
  ]
  return lines.filter((l, idx, arr) => !(l === '' && arr[idx - 1] === '')).join('\n')
}

function renderMemoryIndexFile(memories) {
  const active = memories
    .filter((m) => m.enabled !== false)
    .sort((a, b) => {
      if (Boolean(b.pinned) !== Boolean(a.pinned)) return b.pinned ? 1 : -1
      return (b.updatedAt || 0) - (a.updatedAt || 0)
    })

  const lines = [
    '# Sandbox Memory Index',
    '',
    '<!-- Auto-generated by @metis/sandbox-memory. Edit via Memory Center UI or memory_* tools. -->',
    '',
  ]
  if (active.length === 0) {
    lines.push('_No active memories yet._', '')
  } else {
    for (const m of active) {
      const pinMark = m.pinned ? '📌 ' : ''
      const tagStr = m.tags?.length ? ` [${m.tags.slice(0, 4).join(', ')}]` : ''
      lines.push(`- ${pinMark}\`${m.id}\` **[${m.category}] ${m.title}** — ${m.summary}${tagStr} _(entries/${m.id}.md)_`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

export function createMemoryStore({
  memoryDir,
  config = {},
  env = process.env,
} = {}) {
  const rootDir = memoryDir || resolveMemoryDir(config, env)
  const storeFile = join(rootDir, 'memories.json')
  const indexFile = join(rootDir, 'MEMORY.md')
  const entriesDir = join(rootDir, 'entries')

  const initialSettings = normalizeSettings(config, DEFAULT_SETTINGS)
  let revision = 1
  let state = {
    version: 1,
    settings: initialSettings,
    memories: [],
    stats: {
      totalAutoCaptures: 0,
      totalAgentWrites: 0,
      totalManualWrites: 0,
      totalSearches: 0,
      totalReads: 0,
    },
  }

  function normalizeStoredEntry(raw) {
    if (!raw || typeof raw !== 'object') return null
    const id = String(raw.id || '').trim() || generateMemoryId()
    const content = String(raw.content || '').trim().slice(0, MAX_CONTENT_CHARS)
    const summary = buildSummary(content, raw.summary)
    const title = normalizeTitle(raw.title, summary || content)
    const now = Date.now()
    return {
      id,
      title,
      summary: summary || title,
      content: content || summary || title,
      category: normalizeCategory(raw.category),
      tags: normalizeTags(raw.tags),
      source: normalizeSource(raw.source),
      pinned: Boolean(raw.pinned),
      enabled: raw.enabled !== false,
      dedupeKey: sanitizeDedupeKey(raw.dedupeKey || ''),
      sessionId: String(raw.sessionId || '').trim().slice(0, 96),
      createdAt: Number(raw.createdAt) || now,
      updatedAt: Number(raw.updatedAt) || now,
      lastAccessedAt: Number(raw.lastAccessedAt) || 0,
      accessCount: Math.max(0, Math.trunc(Number(raw.accessCount) || 0)),
    }
  }

  function loadFromDisk() {
    if (!existsSync(storeFile)) return
    try {
      const parsed = JSON.parse(readFileSync(storeFile, 'utf8'))
      if (parsed && typeof parsed === 'object') {
        const list = Array.isArray(parsed.memories)
          ? parsed.memories.map(normalizeStoredEntry).filter(Boolean)
          : []
        state = {
          version: 1,
          settings: normalizeSettings(parsed.settings, initialSettings),
          memories: list.slice(0, MAX_MEMORIES),
          stats: {
            totalAutoCaptures: Number(parsed.stats?.totalAutoCaptures) || 0,
            totalAgentWrites: Number(parsed.stats?.totalAgentWrites) || 0,
            totalManualWrites: Number(parsed.stats?.totalManualWrites) || 0,
            totalSearches: Number(parsed.stats?.totalSearches) || 0,
            totalReads: Number(parsed.stats?.totalReads) || 0,
          },
        }
      }
    } catch {
      // Preserve clean defaults if storage file is unreadable or corrupt
    }
  }

  function syncMarkdownMirror() {
    try {
      mkdirSync(entriesDir, { recursive: true })
      atomicWriteFile(indexFile, renderMemoryIndexFile(state.memories), 0o644)
      const validFiles = new Set()
      for (const m of state.memories) {
        const fileName = `${m.id}.md`
        validFiles.add(fileName)
        atomicWriteFile(join(entriesDir, fileName), renderEntryMarkdown(m), 0o644)
      }
      for (const existing of readdirSync(entriesDir)) {
        if (existing.endsWith('.md') && !validFiles.has(existing)) {
          try { unlinkSync(join(entriesDir, existing)) } catch {}
        }
      }
    } catch {
      // Mirror sync is best-effort; memories.json remains authoritative
    }
  }

  function persist({ syncMirror = true } = {}) {
    revision += 1
    atomicWriteFile(storeFile, `${JSON.stringify(state, null, 2)}\n`, 0o600)
    if (syncMirror) {
      syncMarkdownMirror()
    }
  }

  loadFromDisk()
  // Ensure directory & MEMORY.md exist on clean startup
  if (!existsSync(storeFile)) {
    persist({ syncMirror: true })
  }

  function findDuplicate(candidate) {
    if (candidate.id) {
      const byId = state.memories.find((m) => m.id === candidate.id)
      if (byId) return byId
    }
    if (candidate.dedupeKey) {
      const byKey = state.memories.find((m) => m.dedupeKey && m.dedupeKey === candidate.dedupeKey)
      if (byKey) return byKey
    }
    const cleanTitleLower = candidate.title.toLowerCase()
    for (const existing of state.memories) {
      if (existing.title.toLowerCase() === cleanTitleLower) {
        return existing
      }
      if (existing.category === candidate.category) {
        const titleSim = computeTitleSimilarity(existing.title, candidate.title)
        const sumSim = computeTitleSimilarity(existing.summary, candidate.summary)
        if ((titleSim >= 0.85 && sumSim >= 0.65) || sumSim >= 0.9) {
          return existing
        }
      }
    }
    return null
  }

  function upsert(input = {}, { skipRedaction = false } = {}) {
    const rawContent = String(input.content ?? input.summary ?? input.title ?? '').trim()
    if (!rawContent) {
      return { ok: false, status: 400, error: 'Memory content or summary is required' }
    }

    const source = normalizeSource(input.source || 'manual')
    const shouldRedact = !skipRedaction && source !== 'manual'
    const cleanContentRes = shouldRedact ? redactSecrets(rawContent) : { text: rawContent, redacted: false }
    const cleanSummaryRes = shouldRedact ? redactSecrets(input.summary || '') : { text: String(input.summary || ''), redacted: false }
    const cleanTitleRes = shouldRedact ? redactSecrets(input.title || '') : { text: String(input.title || ''), redacted: false }

    const content = cleanContentRes.text.trim().slice(0, MAX_CONTENT_CHARS)
    const summary = buildSummary(content, cleanSummaryRes.text)
    const title = normalizeTitle(cleanTitleRes.text, summary || content)
    const category = normalizeCategory(input.category)
    const tags = normalizeTags(input.tags)
    const dedupeKey = sanitizeDedupeKey(input.dedupeKey || '')
    const now = Date.now()

    const existing = findDuplicate({
      id: input.id,
      dedupeKey,
      title,
      summary,
      category,
    })

    if (existing) {
      existing.title = title || existing.title
      existing.summary = summary || existing.summary
      existing.content = content || existing.content
      existing.category = category
      existing.tags = tags.length > 0 ? normalizeTags([...existing.tags, ...tags]) : existing.tags
      if (typeof input.pinned === 'boolean') existing.pinned = input.pinned
      if (typeof input.enabled === 'boolean') existing.enabled = input.enabled
      if (dedupeKey) existing.dedupeKey = dedupeKey
      if (input.sessionId) existing.sessionId = String(input.sessionId).slice(0, 96)
      // Preserve 'manual' ownership if user manually curated an entry unless explicitly manual
      if (source === 'manual') existing.source = 'manual'
      existing.updatedAt = now
      persist()
      return {
        ok: true,
        action: 'updated',
        redacted: cleanContentRes.redacted || cleanSummaryRes.redacted || cleanTitleRes.redacted,
        entry: { ...existing },
      }
    }

    const entry = {
      id: generateMemoryId(),
      title,
      summary: summary || title,
      content,
      category,
      tags,
      source,
      pinned: Boolean(input.pinned),
      enabled: input.enabled !== false,
      dedupeKey,
      sessionId: String(input.sessionId || '').trim().slice(0, 96),
      createdAt: now,
      updatedAt: now,
      lastAccessedAt: 0,
      accessCount: 0,
    }

    state.memories.unshift(entry)
    if (state.memories.length > MAX_MEMORIES) {
      // Evict oldest non-pinned, non-manual entries first
      const evictIdx = (() => {
        for (let i = state.memories.length - 1; i >= 0; i -= 1) {
          if (!state.memories[i].pinned && state.memories[i].source !== 'manual') return i
        }
        for (let i = state.memories.length - 1; i >= 0; i -= 1) {
          if (!state.memories[i].pinned) return i
        }
        return state.memories.length - 1
      })()
      state.memories.splice(evictIdx, 1)
    }

    if (source === 'auto') state.stats.totalAutoCaptures += 1
    else if (source === 'agent') state.stats.totalAgentWrites += 1
    else state.stats.totalManualWrites += 1

    persist()
    return {
      ok: true,
      action: 'created',
      redacted: cleanContentRes.redacted || cleanSummaryRes.redacted || cleanTitleRes.redacted,
      entry: { ...entry },
    }
  }

  function update(id, patch = {}, { skipRedaction = false } = {}) {
    const cleanId = String(id || '').trim()
    const target = state.memories.find((m) => m.id === cleanId)
    if (!target) {
      return { ok: false, status: 404, error: `Memory "${cleanId}" not found` }
    }
    const shouldRedact = !skipRedaction && patch.source !== 'manual' && target.source !== 'manual'
    if (patch.title !== undefined) {
      const r = shouldRedact ? redactSecrets(patch.title) : { text: String(patch.title) }
      target.title = normalizeTitle(r.text, target.summary)
    }
    if (patch.content !== undefined) {
      const r = shouldRedact ? redactSecrets(patch.content) : { text: String(patch.content) }
      const nextContent = r.text.trim().slice(0, MAX_CONTENT_CHARS)
      if (!nextContent) {
        return { ok: false, status: 400, error: 'Memory content cannot be empty' }
      }
      target.content = nextContent
      if (patch.summary === undefined) {
        target.summary = buildSummary(nextContent, '')
      }
    }
    if (patch.summary !== undefined) {
      const r = shouldRedact ? redactSecrets(patch.summary) : { text: String(patch.summary) }
      target.summary = buildSummary(target.content, r.text)
    }
    if (patch.category !== undefined) {
      target.category = normalizeCategory(patch.category)
    }
    if (patch.tags !== undefined) {
      target.tags = normalizeTags(patch.tags)
    }
    if (typeof patch.pinned === 'boolean') {
      target.pinned = patch.pinned
    }
    if (typeof patch.enabled === 'boolean') {
      target.enabled = patch.enabled
    }
    if (patch.source !== undefined) {
      target.source = normalizeSource(patch.source)
    }
    target.updatedAt = Date.now()
    persist()
    return { ok: true, entry: { ...target } }
  }

  function remove(id) {
    const cleanId = String(id || '').trim()
    const idx = state.memories.findIndex((m) => m.id === cleanId)
    if (idx < 0) {
      return { ok: false, status: 404, error: `Memory "${cleanId}" not found` }
    }
    const [removed] = state.memories.splice(idx, 1)
    persist()
    return { ok: true, removed }
  }

  function clearBySource(source = 'auto') {
    const cleanSrc = source === 'all' ? 'all' : normalizeSource(source)
    const before = state.memories.length
    if (cleanSrc === 'all') {
      state.memories = []
    } else {
      state.memories = state.memories.filter((m) => m.source !== cleanSrc)
    }
    const removedCount = before - state.memories.length
    if (removedCount > 0) persist()
    return { ok: true, removedCount }
  }

  function get(id, { trackAccess = false } = {}) {
    const cleanId = String(id || '').trim()
    const found = state.memories.find((m) => m.id === cleanId)
    if (!found) return null
    if (trackAccess) {
      found.accessCount = (found.accessCount || 0) + 1
      found.lastAccessedAt = Date.now()
      state.stats.totalReads += 1
      persist({ syncMirror: false })
    }
    return { ...found }
  }

  function getMany(ids = [], { trackAccess = false } = {}) {
    const cleanIds = Array.from(new Set((Array.isArray(ids) ? ids : [ids]).map((x) => String(x || '').trim()).filter(Boolean)))
    const results = []
    let touched = false
    const now = Date.now()
    for (const id of cleanIds) {
      const found = state.memories.find((m) => m.id === id)
      if (!found) continue
      if (trackAccess) {
        found.accessCount = (found.accessCount || 0) + 1
        found.lastAccessedAt = now
        state.stats.totalReads += 1
        touched = true
      }
      results.push({ ...found })
    }
    if (touched) persist({ syncMirror: false })
    return results
  }

  function list() {
    return state.memories
      .slice()
      .sort((a, b) => {
        if (Boolean(b.pinned) !== Boolean(a.pinned)) return b.pinned ? 1 : -1
        return (b.updatedAt || 0) - (a.updatedAt || 0)
      })
      .map((m) => ({ ...m }))
  }

  function search(query, opts = {}, { trackSearch = false } = {}) {
    if (trackSearch) {
      state.stats.totalSearches += 1
      persist({ syncMirror: false })
    }
    return rankMemories(state.memories, query, opts)
  }

  function getSettings() {
    return normalizeSettings(state.settings, DEFAULT_SETTINGS)
  }

  function updateSettings(patch = {}) {
    state.settings = normalizeSettings({
      ...state.settings,
      ...(patch && typeof patch === 'object' ? patch : {}),
      envSections: {
        ...(state.settings.envSections || {}),
        ...(patch?.envSections && typeof patch.envSections === 'object' ? patch.envSections : {}),
      },
    }, DEFAULT_SETTINGS)
    persist({ syncMirror: false })
    return getSettings()
  }

  function exportData() {
    return {
      format: 'dsh-sandbox-memory/v1',
      exportedAt: new Date().toISOString(),
      settings: getSettings(),
      memories: list(),
    }
  }

  function importData(payload, { mode = 'merge' } = {}) {
    if (!payload || typeof payload !== 'object') {
      return { ok: false, status: 400, error: 'Invalid import payload' }
    }
    const items = Array.isArray(payload.memories)
      ? payload.memories
      : Array.isArray(payload)
        ? payload
        : null
    if (!items) {
      return { ok: false, status: 400, error: 'Import payload must contain a memories array' }
    }
    if (mode === 'replace') {
      state.memories = []
    }
    let imported = 0
    for (const raw of items.slice(0, MAX_MEMORIES)) {
      if (!raw || typeof raw !== 'object') continue
      const res = upsert(
        {
          id: mode === 'replace' ? undefined : raw.id,
          title: raw.title,
          summary: raw.summary,
          content: raw.content,
          category: raw.category,
          tags: raw.tags,
          source: raw.source || 'manual',
          pinned: Boolean(raw.pinned),
          enabled: raw.enabled !== false,
          dedupeKey: raw.dedupeKey || '',
        },
        { skipRedaction: true },
      )
      if (res.ok) imported += 1
    }
    if (payload.settings && typeof payload.settings === 'object') {
      updateSettings(payload.settings)
    }
    return { ok: true, imported, total: state.memories.length }
  }

  function getStats() {
    const all = state.memories
    const enabledCount = all.filter((m) => m.enabled !== false).length
    const byCategory = {}
    const bySource = { auto: 0, agent: 0, manual: 0 }
    for (const m of all) {
      byCategory[m.category] = (byCategory[m.category] || 0) + 1
      bySource[m.source] = (bySource[m.source] || 0) + 1
    }
    return {
      total: all.length,
      enabled: enabledCount,
      disabled: all.length - enabledCount,
      pinned: all.filter((m) => m.pinned).length,
      byCategory,
      bySource,
      ...state.stats,
    }
  }

  return {
    rootDir,
    storeFile,
    indexFile,
    entriesDir,
    getRevision: () => revision,
    list,
    get,
    getMany,
    upsert,
    update,
    remove,
    clearBySource,
    search,
    getSettings,
    updateSettings,
    exportData,
    importData,
    getStats,
  }
}
