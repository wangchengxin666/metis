export function resolveLang(activeLocale) {
  return String(activeLocale || '').toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function createTranslator(activeLocale) {
  const dict = resolveLang(activeLocale) === 'zh' ? zh : en
  return (key, vars = null) => {
    let text = dict[key] ?? en[key] ?? key
    if (vars && typeof vars === 'object') {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
      }
    }
    return text
  }
}
